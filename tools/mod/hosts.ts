import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * The modules a Mod may get from its host (`host.get(id)`), generated from the files under assets/scripts: every
 * module of a host's directories, by its path there without the extension (`client/plants/PlantView`), a directory's
 * index by the directory (`shared/protocol`). `createModHost` adds the few values that are no module.
 */
const SCRIPTS = join(resolve(dirname(fileURLToPath(import.meta.url)), '../..'), 'assets/scripts')

export interface HostModules {
    /** The generated file, under assets/scripts. */
    readonly file: string
    readonly exportName: string
    readonly side: string
    /** The directories under assets/scripts whose modules the host gives. */
    readonly roots: readonly string[]
}

export const HOSTS: readonly HostModules[] = [
    { file: 'client/content/hostModules.ts', exportName: 'CLIENT_HOST_MODULES', side: 'client', roots: ['client', 'shared', 'platform', 'core'] },
    { file: 'server/session/hostModules.ts', exportName: 'SERVER_HOST_MODULES', side: 'server', roots: ['server', 'shared', 'ecs'] },
]

/** The hosts' own files, which give the modules rather than being given. */
const SKIPPED = new Set(['client/content/createModHost', 'server/session/createModHost', ...HOSTS.map(host => host.file.replace(/\.ts$/, ''))])

function moduleIds(root: string): string[] {
    const ids: string[] = []
    const walk = (dir: string) => {
        for (const entry of readdirSync(join(SCRIPTS, dir), { withFileTypes: true })) {
            const path = `${dir}/${entry.name}`
            if (entry.isDirectory()) walk(path)
            else if (entry.name.endsWith('.ts') && !entry.name.endsWith('.d.ts')) {
                const id = path.slice(0, -'.ts'.length)
                if (!SKIPPED.has(id)) ids.push(id.endsWith('/index') ? id.slice(0, -'/index'.length) : id)
            }
        }
    }
    walk(root)
    return ids
}

/** The generated file's text for a host. */
export function hostModulesSource(host: HostModules): string {
    const ids = host.roots.flatMap(moduleIds).sort()
    const lines = [
        `// Generated by \`npm run mod:hosts\` (tools/mod/hosts.ts) from the modules under ${host.roots.join(', ')}; run it again`,
        '// after adding, moving or removing one. tests/architecture/host-modules.test.ts checks it.',
        ...ids.map((id, index) => `import * as m${index} from '@/${id}'`),
        '',
        `/** Every module a ${host.side} Mod may get from its host, by its path under assets/scripts. */`,
        `export const ${host.exportName}: Readonly<Record<string, unknown>> = {`,
        ...ids.map((id, index) => `    '${id}': m${index},`),
        '}',
        '',
    ]
    return lines.join('\n')
}

/** Writes the hosts' module lists; true when one changed. */
export function writeHostModules(): boolean {
    let changed = false
    for (const host of HOSTS) {
        const path = join(SCRIPTS, host.file), text = hostModulesSource(host)
        let current = ''
        try { current = readFileSync(path, 'utf8') } catch { /* a new list */ }
        if (current === text) continue
        writeFileSync(path, text)
        changed = true
        console.log(`[mod] Wrote ${path}`)
    }
    return changed
}
