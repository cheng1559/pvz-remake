import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { test } from 'node:test'
import { resolve } from 'node:path'

const source = (file: string) => readFileSync(resolve(process.cwd(), file), 'utf8')

test('Adventure 1-1 presentation waits for entity creation and redraws restored HUD state', () => {
    const entities = source('assets/scripts/client/level/LevelEntityRenderer.ts')
    const particles = source('assets/scripts/client/level/LevelParticlePresenter.ts')
    const view = source('assets/scripts/client/level/LevelView.ts')
    const showcase = source('assets/scripts/client/level/LevelScene.ts')
    const input = source('assets/scripts/client/level/LevelInputPresenter.ts')
    const hud = source('assets/scripts/client/level/LevelHudPresenter.ts')
    const end = source('assets/scripts/client/level/LevelEndPresenter.ts')
    const probe = source('assets/scripts/app/LevelController.ts')
    const app = source('assets/scripts/app/GameApp.ts')

    assert.match(entities, /async snapshot\(\)[^{]*\{\s*await Promise\.all\(this\.creationTasks\.values\(\)\)/)
    assert.match(view, /const \[entities, particles\] = await Promise\.all\(\[\s*this\.entityRenderer\.snapshot\(\),\s*this\.particles\.snapshot\(\)/)
    assert.match(particles, /await Promise\.all\(players\.map\(player => player\.whenReady\(\)\)\)/)
    assert.match(particles, /name: 'ParticleSystem',\s*parent,/)
    assert.match(view, /this\.end\.sync\(snapshot, events\)\s*for \(const item of snapshot\.items\) this\.end\.syncAward\(item, snapshot\.levelId\)/)
    assert.match(showcase, /const level = await this\.view\.snapshot\(/)
    assert.match(showcase, /this\.snapshotting = true\s*this\.input\.suspend\(\)\s*try \{/)
    assert.match(showcase, /finally \{\s*this\.snapshotting = false\s*if \(!this\.game\.render\(\)\.paused\) this\.input\.resume\(\)/)
    assert.match(showcase, /if \(this\.snapshotting \|\| this\.completing \|\| this\.gameOverNotified \|\| !this\.game/)
    assert.match(input, /private enabled = false/)
    assert.match(input, /if \(!this\.enabled \|\| !this\.view\.introComplete\) return/)
    assert.match(input, /const extra = definition \? 15 : 0/)
    assert.match(hud, /this\.syncSun\(world\.sun\)/)
    assert.match(hud, /this\.syncSeedPacket\(world, \[\], this\.lastIntroComplete, false\)/)
    assert.match(hud, /const visible = introComplete && snapshot\.result !== 'lost'/)
    assert.match(hud, /this\.seedBank\.sync\(/)
    assert.match(showcase, /if \(!this\.lifecycle\.onComplete\) return/)
    assert.match(showcase, /snapshot\.result === 'lost'[\s\S]*?this\.lifecycle\.onGameOver/)
    assert.doesNotMatch(view, /ProfileStore/)
    assert.match(view, /static async create\(root: Node, content: LoadedContent, levelId: string, playerName: string, initial: WorldSnapshot\)/)
    assert.match(probe, /const playerName = profile\?\.name \|\| 'Player'/)
    assert.match(probe, /LevelView\.create\(root, content, save\?\.levelId \?\? levelId, playerName, game\.render\(\)\)/)
    assert.match(app, /createLevelController\(this\.gameLayer, \{/)
    assert.match(app, /onComplete: \(\) => this\.finish\(/)
    assert.match(app, /onGameOver: \(\) => this\.finish\(/)
    assert.match(app, /installLevelProbe\(this\.controller\)/)
    assert.doesNotMatch(app, /@\/(?:ui|game)\//)
})
